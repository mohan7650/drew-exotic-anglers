// Post-build: give specific routes their own share-preview metadata.
//
// Social crawlers (WhatsApp, Facebook, LinkedIn, X) don't run JavaScript, so they
// only see the <head> of the HTML the server returns. The SPA serves the same
// index.html for every path, so every URL previews as the homepage. For each page
// below we write a copy of build/index.html with page-specific meta tags, plus a
// build/tour/.htaccess rule so LiteSpeed serves that copy for the exact URL.
// The React app inside the copy is identical, so the page renders normally.

const fs = require('fs');
const path = require('path');

const SITE = 'https://drewsguideservice.com';
const BUILD = path.join(__dirname, '..', 'build');

const PAGES = [
  {
    slug: 'brazil-eco-lodge-da-barra',
    title: 'EcoLodge da Barra — Amazon Fly Fishing | Drew’s Guide Service',
    ogTitle: 'EcoLodge da Barra — Amazon Fly Fishing Experience',
    description:
      'Five full days of guided fly fishing from a floating lodge where the Juruena and Teles Pires rivers meet in Mato Grosso, Brazil. Target 20+ Amazon species with Drew’s Guide Service.',
    image: '/images/ecolodge/og-ecolodge-da-barra.jpg',
    imageType: 'image/jpeg',
    imageAlt: 'EcoLodge da Barra — two anglers holding a large payara caught on the fly in the Amazon',
    icon: '/images/ecolodge/favicon-ecolodge.png',
  },
];

function escapeAttr(s) {
  return s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

// Replace the content="" of an existing tag; fail the build if the tag is missing
// so a change to public/index.html can't silently break the share preview.
function setMeta(html, attr, key, value) {
  const re = new RegExp(`(<meta\\s+${attr}="${key}"\\s+content=")[^"]*(")`);
  if (!re.test(html)) throw new Error(`[og-pages] <meta ${attr}="${key}"> not found in build/index.html`);
  return html.replace(re, `$1${escapeAttr(value)}$2`);
}

function replaceOrFail(html, re, replacement, label) {
  if (!re.test(html)) throw new Error(`[og-pages] ${label} not found in build/index.html`);
  return html.replace(re, replacement);
}

const base = fs.readFileSync(path.join(BUILD, 'index.html'), 'utf8');
fs.mkdirSync(path.join(BUILD, 'tour'), { recursive: true });

const rules = [];

for (const page of PAGES) {
  const url = `${SITE}/tour/${page.slug}`;
  const image = `${SITE}${page.image}`;
  let html = base;

  html = replaceOrFail(html, /<title>[^<]*<\/title>/, `<title>${escapeAttr(page.title)}</title>`, '<title>');
  html = replaceOrFail(html, /(<link\s+rel="canonical"\s+href=")[^"]*(")/, `$1${url}$2`, 'canonical link');
  html = setMeta(html, 'name', 'description', page.description);
  if (page.icon) {
    html = replaceOrFail(html, /<link\s+rel="icon"[^>]*>/, `<link rel="icon" type="image/png" href="${page.icon}"/>`, 'icon link');
  }

  html = setMeta(html, 'property', 'og:url', url);
  html = setMeta(html, 'property', 'og:title', page.ogTitle);
  html = setMeta(html, 'property', 'og:description', page.description);
  html = setMeta(html, 'property', 'og:image', image);
  html = setMeta(html, 'property', 'og:image:type', page.imageType);
  html = setMeta(html, 'property', 'og:image:width', '1200');
  html = setMeta(html, 'property', 'og:image:height', '630');
  html = setMeta(html, 'property', 'og:image:alt', page.imageAlt);

  html = setMeta(html, 'name', 'twitter:card', 'summary_large_image');
  html = setMeta(html, 'name', 'twitter:title', page.ogTitle);
  html = setMeta(html, 'name', 'twitter:description', page.description);
  html = setMeta(html, 'name', 'twitter:image', image);
  html = setMeta(html, 'name', 'twitter:image:alt', page.imageAlt);

  fs.writeFileSync(path.join(BUILD, 'tour', `${page.slug}.html`), html);
  rules.push(`RewriteRule ^${page.slug.replace(/[.-]/g, '\\$&')}/?$ ${page.slug}.html [L]`);
  console.log(`[og-pages] wrote build/tour/${page.slug}.html`);
}

// A per-directory .htaccess replaces (does not inherit) the root rewrite rules,
// so it repeats the SPA fallback for every other /tour/* URL.
const htaccess = `# Generated by scripts/og-pages.js — do not edit in build/.
# Serves pre-rendered share metadata for specific tour pages; everything
# else under /tour/ falls back to the React app like the rest of the site.
<IfModule mod_rewrite.c>
  RewriteEngine On
  ${rules.join('\n  ')}
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteRule ^ /index.html [L]
</IfModule>
`;
fs.writeFileSync(path.join(BUILD, 'tour', '.htaccess'), htaccess);
console.log('[og-pages] wrote build/tour/.htaccess');
